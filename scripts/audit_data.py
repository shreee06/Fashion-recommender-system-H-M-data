"""Audit the processed H&M parquet tables and write docs/data_audit.md.

Memory-light: transactions are streamed by row group and ids are mapped to
integer codes against articles/customers, so no string column is held in full.
"""
import sys
from pathlib import Path

import numpy as np
import pyarrow as pa
import pyarrow.compute as pc
import pyarrow.parquet as pq

ROOT = Path(__file__).resolve().parents[1]
PROC = ROOT / "data" / "processed"
OUT = ROOT / "docs" / "data_audit.md"


def null_counts(path):
    pf = pq.ParquetFile(path)
    names = pf.schema_arrow.names
    totals = dict.fromkeys(names, 0)
    for i in range(pf.num_row_groups):
        t = pf.read_row_group(i)
        for n in names:
            totals[n] += t[n].null_count
    return pf.metadata.num_rows, totals


def code_ids(values, table_ids):
    """Map string ids to positions in `table_ids`; -1 where absent."""
    idx = pc.index_in(values, value_set=table_ids)
    return pc.fill_null(idx, -1).to_numpy(zero_copy_only=False).astype(np.int64)


def md_table(rows, header):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def main():
    art_ids = pq.read_table(PROC / "articles.parquet", columns=["article_id"])["article_id"].combine_chunks()
    cust_ids = pq.read_table(PROC / "customers.parquet", columns=["customer_id"])["customer_id"].combine_chunks()
    n_art, n_cust = len(art_ids), len(cust_ids)

    pf = pq.ParquetFile(PROC / "transactions_train.parquet")
    days, ccode, acode, price, chan = [], [], [], [], []
    for i in range(pf.num_row_groups):
        t = pf.read_row_group(i)
        days.append(t["t_dat"].cast(pa.int32()).to_numpy())
        ccode.append(code_ids(t["customer_id"], cust_ids))
        acode.append(code_ids(t["article_id"], art_ids))
        price.append(t["price"].to_numpy())
        chan.append(t["sales_channel_id"].to_numpy())
    days, ccode, acode = map(np.concatenate, (days, ccode, acode))
    price, chan = np.concatenate(price), np.concatenate(chan)
    n = len(days)

    # keys cover only ids that exist in the dimension tables; missing ids share a bucket
    missing_c = int((ccode < 0).sum())
    missing_a = int((acode < 0).sum())
    ccode[ccode < 0] = n_cust
    acode[acode < 0] = n_art

    # unique ids that appear in transactions but not in the dimension tables
    miss_art_rows = []
    miss_cust_rows = []
    for i in range(pf.num_row_groups):
        t = pf.read_row_group(i, columns=["customer_id", "article_id"])
        a = t["article_id"]
        c = t["customer_id"]
        miss_art_rows.append(pc.unique(pc.filter(a, pc.invert(pc.is_in(a, value_set=art_ids)))))
        miss_cust_rows.append(pc.unique(pc.filter(c, pc.invert(pc.is_in(c, value_set=cust_ids)))))
    miss_art_unique = len(pc.unique(pa.chunked_array(miss_art_rows)))
    miss_cust_unique = len(pc.unique(pa.chunked_array(miss_cust_rows)))

    # whole-row duplicates
    key1 = (((ccode.astype(np.uint64) << 17) | acode.astype(np.uint64)) << 10) | (days - days.min()).astype(np.uint64)
    key2 = (price.view(np.uint32).astype(np.uint64) << 8) | chan.astype(np.uint64)
    order = np.lexsort((key2, key1))
    k1, k2 = key1[order], key2[order]
    dup_rows = int(((k1[1:] == k1[:-1]) & (k2[1:] == k2[:-1])).sum())
    del order, k1, k2, key1, key2

    d0, d1 = int(days.min()), int(days.max())
    epoch = np.datetime64("1970-01-01")
    date_min, date_max = epoch + np.timedelta64(d0, "D"), epoch + np.timedelta64(d1, "D")

    per_cust = np.bincount(ccode[ccode < n_cust], minlength=n_cust)
    active = per_cust[per_cust > 0]
    per_art = np.bincount(acode[acode < n_art], minlength=n_art)

    week = (days - d0) // 7
    weekly = np.bincount(week)
    week_start = [str(epoch + np.timedelta64(d0 + 7 * w, "D")) for w in range(len(weekly))]
    top = np.argsort(weekly)[::-1][:5]

    chan_counts = {int(k): int((chan == k).sum()) for k in np.unique(chan)}
    p = price.astype(np.float64)

    L = ["# Data audit", "",
         "Generated by `scripts/audit_data.py` from `data/processed/*.parquet`. All figures are computed from the real data.", ""]
    L += ["## Row counts", "", md_table([
        ("articles", f"{n_art:,}"), ("customers", f"{n_cust:,}"), ("transactions_train", f"{n:,}")],
        ["table", "rows"]), ""]
    L += ["## Transactions", "",
          f"- Date range: {date_min} to {date_max} ({d1 - d0 + 1} days, {len(weekly)} week buckets)",
          f"- Unique customers with at least one purchase: {len(active):,} (of {n_cust:,} in customers.csv)",
          f"- Unique articles purchased: {int((per_art > 0).sum()):,} (of {n_art:,} in articles.csv)",
          f"- Rows per sales_channel_id: {chan_counts}",
          f"- Exact duplicate rows (same date, customer, article, price, channel): {dup_rows:,} "
          f"({dup_rows / n:.2%} of rows). Per the dataset description these are legitimate repeat purchases "
          f"(same item bought more than once on the same day), so they are kept.",
          f"- Price (normalised, as provided): min {p.min():.6f}, median {np.median(p):.6f}, max {p.max():.6f}", ""]
    L += ["## Null counts per column", ""]
    for name in ("articles", "customers", "transactions_train"):
        rows, nulls = null_counts(PROC / f"{name}.parquet")
        L += [f"**{name}** ({rows:,} rows)", "",
              md_table([(k, f"{v:,}", f"{v / rows:.2%}") for k, v in nulls.items()], ["column", "nulls", "share"]), ""]
    L += ["## Purchases per customer (customers with at least one purchase)", "",
          md_table([
              ("median", f"{np.median(active):g}"),
              ("mean", f"{active.mean():.2f}"),
              ("90th percentile", f"{np.percentile(active, 90):g}"),
              ("max", f"{active.max():,}"),
              ("share with exactly 1 purchase", f"{(active == 1).mean():.2%}"),
              ("customers in customers.csv with 0 purchases", f"{int((per_cust == 0).sum()):,} ({(per_cust == 0).mean():.2%})"),
          ], ["statistic", "value"]), ""]
    L += ["## Weekly transaction volume", "",
          f"Weeks start on {week_start[0]} (first transaction day; the last bucket may be partial).", "",
          md_table([
              ("weeks", len(weekly)),
              ("min", f"{weekly.min():,}"),
              ("median", f"{int(np.median(weekly)):,}"),
              ("mean", f"{weekly.mean():,.0f}"),
              ("max", f"{weekly.max():,}"),
              ("busiest weeks", ", ".join(f"{week_start[i]} ({weekly[i]:,})" for i in top)),
          ], ["statistic", "value"]), ""]
    L += ["## Referential integrity", "",
          md_table([
              ("article_ids in transactions missing from articles.csv", f"{miss_art_unique:,} unique ({missing_a:,} rows)"),
              ("customer_ids in transactions missing from customers.csv", f"{miss_cust_unique:,} unique ({missing_c:,} rows)"),
          ], ["check", "result"]), ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(L))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    sys.exit(main())
